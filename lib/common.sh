# shellcheck shell=bash
# Shared helpers for the `sandbox` CLI.
# NOTE: must stay compatible with macOS' default bash 3.2 (no associative arrays,
# no ${var,,}, no mapfile, no `local -n`).

SANDBOX_HOME="${AGENT_SANDBOX_HOME:-$HOME/.agent-sandbox}"
SANDBOXES_DIR="$SANDBOX_HOME/sandboxes"

if [ -t 2 ]; then
  C_RED=$'\033[31m'; C_YEL=$'\033[33m'; C_BLU=$'\033[34m'; C_GRN=$'\033[32m'; C_BLD=$'\033[1m'; C_RST=$'\033[0m'
else
  C_RED=""; C_YEL=""; C_BLU=""; C_GRN=""; C_BLD=""; C_RST=""
fi

log()  { printf '%s==>%s %s\n' "$C_BLU" "$C_RST" "$*" >&2; }
ok()   { printf '%s✔%s %s\n' "$C_GRN" "$C_RST" "$*" >&2; }
warn() { printf '%sWARN:%s %s\n' "$C_YEL" "$C_RST" "$*" >&2; }
die()  { printf '%sERROR:%s %s\n' "$C_RED" "$C_RST" "$*" >&2; exit 1; }

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "Required command '$1' not found. ${2:-}"
}

host_os() {
  case "$(uname -s)" in
    Darwin) echo macos ;;
    Linux)  echo linux ;;
    *)      echo unknown ;;
  esac
}

# Every variable that is frozen into a sandbox's sandbox.env at creation time.
SANDBOX_VARS="NAME CPUS MEMORY_GIB DISK_GIB NETWORK_MODE ALLOWLISTS EXTRA_ALLOW_DOMAINS
ALLOW_CIDRS AGENT_DNS UPSTREAM_PROXY GIT_HOST GH_HOST COPILOT_HOST REPO_URL
GIT_USER_NAME GIT_USER_EMAIL JDK_VERSIONS GRADLE_VERSION MAVEN_VERSION NODE_MAJOR COPILOT_VERSION
EXTRA_APT_PACKAGES AGENT_CMD AGENT_PROMPT_ARG LIMA_INSTANCE LIMA_SSH_PORT"

# Subset passed into the guest (never contains host paths or host secrets).
GUEST_VARS="NAME NETWORK_MODE ALLOW_CIDRS AGENT_DNS UPSTREAM_PROXY GIT_HOST
GH_HOST COPILOT_HOST REPO_URL GIT_USER_NAME GIT_USER_EMAIL JDK_VERSIONS GRADLE_VERSION
MAVEN_VERSION NODE_MAJOR COPILOT_VERSION EXTRA_APT_PACKAGES AGENT_CMD AGENT_PROMPT_ARG"

var_value() {
  # Prints the value of the variable named $1 (empty if unset). Works with `set -u` on bash 3.2.
  eval "printf '%s' \"\${$1-}\""
}

load_config() {
  # shellcheck source=/dev/null
  . "$ROOT_DIR/config/defaults.conf"
  if [ -f "$ROOT_DIR/config/sandbox.conf" ]; then
    # shellcheck source=/dev/null
    . "$ROOT_DIR/config/sandbox.conf"
  fi
}

validate_name() {
  case "$1" in
    ""|*[!a-z0-9-]*|-*) die "Invalid sandbox name '$1' (use lowercase letters, digits and '-')" ;;
  esac
  [ "${#1}" -le 30 ] || die "Sandbox name too long (max 30 chars)"
}

save_sandbox_env() {
  local f="$SBX_DIR/sandbox.env" v
  : > "$f"
  chmod 600 "$f"
  for v in $SANDBOX_VARS; do
    printf '%s=%q\n' "$v" "$(var_value "$v")" >> "$f"
  done
}

write_guest_env() {
  local v
  echo "# Generated by agent-sandbox on the host. Overwritten by 'sandbox provision' / 'sandbox network'."
  for v in $GUEST_VARS; do
    printf '%s=%q\n' "$v" "$(var_value "$v")"
  done
}

# Load a sandbox by name: defaults first (for keys added after creation), then frozen values.
load_sandbox() {
  local name="${1:-}"
  [ -n "$name" ] || die "Missing sandbox NAME. See 'sandbox help'."
  validate_name "$name"
  SBX_DIR="$SANDBOXES_DIR/$name"
  [ -f "$SBX_DIR/sandbox.env" ] || die "No sandbox named '$name'. See 'sandbox list'."
  load_config
  # shellcheck source=/dev/null
  . "$SBX_DIR/sandbox.env"
}

# Quote arguments so they survive one round of remote shell parsing.
quote_args() {
  local out="" a
  for a in "$@"; do out="$out $(printf '%q' "$a")"; done
  printf '%s' "${out# }"
}

git_host_from_url() {
  # git@host:org/repo.git | ssh://git@host[:port]/org/repo.git | https://host/org/repo(.git)
  local u="$1" h
  case "$u" in
    *://*) h="${u#*://}"; h="${h#*@}"; h="${h%%/*}"; h="${h%%:*}" ;;
    *@*:*) h="${u#*@}"; h="${h%%:*}" ;;
    *) h="" ;;
  esac
  printf '%s' "$h"
}

repo_path_from_url() {
  # -> org/repo (without .git)
  local u="$1" p
  case "$u" in
    *://*) p="${u#*://}"; p="${p#*/}" ;;
    *@*:*) p="${u#*:}" ;;
    *) p="" ;;
  esac
  p="${p%.git}"
  printf '%s' "$p"
}

# One sandbox works on one repository, reached over SSH with a deploy key generated in the VM.
validate_ssh_repo_url() {
  local u="$1" h p port
  case "$u" in
    git@*:*|ssh://*) ;;
    http://*|https://*) die "Use the SSH clone URL (e.g. git@github.com:org/repo.git), not '$u'" ;;
    *) die "Not an SSH git URL: '$u' (expected git@host:org/repo.git or ssh://git@host/org/repo.git)" ;;
  esac
  case "$u" in *[[:space:]\'\"\;\&\|\$\`\<\>\(\)]*) die "Invalid characters in '$u'" ;; esac
  h="$(git_host_from_url "$u")"
  p="$(repo_path_from_url "$u")"
  [ -n "$h" ] || die "Cannot parse the git host from '$u'"
  case "$p" in */*) ;; *) die "Cannot parse org/repo from '$u'" ;; esac
  [ -n "${p##*/}" ] || die "Cannot parse the repository name from '$u'"
  case "$u" in
    ssh://*)
      port="${u#ssh://}"; port="${port#*@}"; port="${port%%/*}"
      case "$port" in *:*) [ "${port##*:}" = 22 ] || die "Only SSH port 22 is supported by the egress proxy ('$u')" ;; esac ;;
  esac
}

repo_dir_from_url() {
  local p
  p="$(repo_path_from_url "$1")"
  printf '%s' "${p##*/}"
}

build_allowlist() {
  local list f
  echo "# Domain allowlist for sandbox '$NAME' (one per line; '.example.com' or '*.example.com' = incl. subdomains)."
  echo "# Add entries with: sandbox allow $NAME <domain>   (or edit this file, then: sandbox network $NAME $NETWORK_MODE)"
  for list in $ALLOWLISTS; do
    f="$ROOT_DIR/config/allowlist/$list.txt"
    [ -f "$f" ] || die "Allowlist '$list' not found ($f)"
    echo
    echo "# ---- $list ----"
    grep -v '^[[:space:]]*$' "$f" || true
  done
  if [ -f "$ROOT_DIR/config/allowlist.local.txt" ]; then
    echo
    echo "# ---- allowlist.local.txt ----"
    grep -v '^[[:space:]]*$' "$ROOT_DIR/config/allowlist.local.txt" || true
  fi
  if [ -n "${EXTRA_ALLOW_DOMAINS:-}" ]; then
    echo
    echo "# ---- EXTRA_ALLOW_DOMAINS ----"
    for f in $EXTRA_ALLOW_DOMAINS; do echo "$f"; done
  fi
}

ssh_common_opts() {
  # -F /dev/null ignores ~/.ssh/config, so a global "ForwardAgent yes" can never leak into the VM.
  printf '%s\n' -F /dev/null \
    -i "$SBX_DIR/id_ed25519" \
    -o IdentitiesOnly=yes \
    -o "UserKnownHostsFile=$SBX_DIR/known_hosts" \
    -o StrictHostKeyChecking=accept-new \
    -o "HostKeyAlias=agent-sandbox-$NAME" \
    -o ForwardAgent=no -o ForwardX11=no -o ClearAllForwardings=yes \
    -o PermitLocalCommand=no -o ControlMaster=no -o ControlPath=none \
    -o ServerAliveInterval=30 -o LogLevel=ERROR
}

# agent_ssh [-t] [remote command string]   -- connects as the unprivileged 'agent' user
agent_ssh() {
  local tty="-T" host port endpoint old_ifs
  if [ "${1:-}" = "-t" ]; then
    shift
    if [ -t 0 ]; then tty="-tt"; fi
  fi
  endpoint="$(vm_ssh_endpoint)"
  host="${endpoint% *}"; port="${endpoint#* }"
  old_ifs="$IFS"; IFS=$'\n'
  # shellcheck disable=SC2046
  set -- $(ssh_common_opts) "$tty" -p "$port" "agent@$host" "$@"
  IFS="$old_ifs"
  ssh "$@"
}

ensure_running() {
  if [ "$(vm_status)" != "running" ]; then
    log "Starting sandbox '$NAME'"
    vm_start
  fi
}

# Upload guest scripts + config and run guest/provision.sh as root inside the VM.
provision_guest() {
  local stage f
  stage="$(mktemp -d "${TMPDIR:-/tmp}/agent-sandbox.XXXXXX")"
  mkdir -p "$stage/certs" "$stage/home"
  cp -R "$ROOT_DIR/guest/." "$stage/"
  cp "$SBX_DIR/allowlist.txt" "$stage/allowlist.txt"
  cp "$SBX_DIR/id_ed25519.pub" "$stage/host_access_key.pub"
  for f in "$ROOT_DIR"/config/certs/*.crt; do
    if [ -f "$f" ]; then cp "$f" "$stage/certs/"; fi
  done
  if [ -d "$ROOT_DIR/config/home" ]; then
    (cd "$ROOT_DIR/config/home" && COPYFILE_DISABLE=1 tar -cf - --exclude README.md .) | (cd "$stage/home" && tar -xf -)
  fi
  write_guest_env > "$stage/sandbox.env"

  log "Uploading provisioning bundle into the VM"
  (cd "$stage" && COPYFILE_DISABLE=1 tar -cf - .) | vm_admin_exec bash -c \
    'rm -rf /opt/agent-sandbox/stage && mkdir -p /opt/agent-sandbox/stage && tar --warning=no-unknown-keyword --no-same-owner -C /opt/agent-sandbox/stage -xf -'
  rm -rf "$stage"

  log "Provisioning guest (packages, JDKs, Gradle, Maven, Copilot CLI, egress policy). First run takes a few minutes."
  vm_admin_exec bash /opt/agent-sandbox/stage/provision.sh
}

# Push network policy (mode, CIDRs, allowlist) into the VM and re-apply it live.
push_network() {
  write_guest_env | vm_admin_exec bash -c 'umask 077; cat > /etc/agent-sandbox/sandbox.env'
  vm_admin_exec bash -c 'cat > /etc/agent-sandbox/allowlist.txt' < "$SBX_DIR/allowlist.txt"
  vm_admin_exec /opt/agent-sandbox/bin/apply-network
}
