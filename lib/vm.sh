# shellcheck shell=bash
# VM lifecycle via Lima: a full Linux VM using Apple Virtualization.framework ("vz") on
# macOS, or QEMU/KVM on Linux. Same guest and settings on both. Hardened: plain mode (no guest agent), no mounts, no port
# forwarding, no SSH agent forwarding, no proxy env propagation.

vm_setup() {
  local os ver major
  os="$(host_os)"
  if ! command -v limactl >/dev/null 2>&1; then
    if [ "$os" = macos ] && command -v brew >/dev/null 2>&1; then
      log "Installing Lima via Homebrew"
      brew install lima
    else
      die "Lima is not installed. See https://lima-vm.io/docs/installation/ (macOS: 'brew install lima')."
    fi
  fi
  ver="$(limactl --version 2>/dev/null | awk '{print $NF}')"
  major="${ver%%.*}"
  case "$major" in ''|*[!0-9]*) die "Could not parse Lima version from '$(limactl --version 2>&1)'" ;; esac
  [ "$major" -ge 2 ] || die "Lima >= 2.0 is required (found $ver). Upgrade: brew upgrade lima"
  ok "Lima $ver"

  if [ "$os" = macos ]; then
    local mv; mv="$(sw_vers -productVersion)"
    case "$mv" in
      1[0-2].*|13.[0-4]*) die "macOS 13.5+ is required for Apple Virtualization.framework (found $mv)" ;;
    esac
    ok "macOS $mv ($(uname -m)) — VMs use Apple Virtualization.framework (vz)"
  else
    [ -e /dev/kvm ] || die "/dev/kvm not found. Enable virtualization in BIOS/UEFI and load the kvm module."
    need_cmd "qemu-system-$(uname -m)" "Install QEMU (e.g. 'sudo apt install qemu-system')."
    ok "QEMU + KVM available"
  fi
  need_cmd ssh
  need_cmd ssh-keygen
  need_cmd git
  ok "Host setup complete. Next: ./sandbox create <name> git@github.com:<org>/<repo>.git"
}

lima_pick_port() {
  local p used
  used="$(grep -h '^LIMA_SSH_PORT=' "$SANDBOXES_DIR"/*/sandbox.env 2>/dev/null | cut -d= -f2 || true)"
  p=52201
  while [ "$p" -lt 52999 ]; do
    if ! printf '%s\n' "$used" | grep -qx "$p" && ! nc -z 127.0.0.1 "$p" >/dev/null 2>&1; then
      echo "$p"; return 0
    fi
    p=$((p + 1))
  done
  die "No free SSH port found in 52201-52999"
}

lima_render_yaml() {
  local vmtype=qemu
  [ "$(host_os)" = macos ] && vmtype=vz
  cat <<EOF
# Generated by agent-sandbox for sandbox '$NAME'. Re-create the sandbox instead of editing.
minimumLimaVersion: "2.0.0"
vmType: "$vmtype"

# Plain mode: no Lima guest agent, no mounts, no dynamic port forwarding, no containerd,
# no SSH agent forwarding, no host clock sync. The VM behaves like a separate machine.
plain: true

cpus: $CPUS
memory: "${MEMORY_GIB}GiB"
disk: "${DISK_GIB}GiB"

images:
  - location: "https://cloud-images.ubuntu.com/releases/noble/release/ubuntu-24.04-server-cloudimg-arm64.img"
    arch: "aarch64"
  - location: "https://cloud-images.ubuntu.com/releases/noble/release/ubuntu-24.04-server-cloudimg-amd64.img"
    arch: "x86_64"

# Never share host directories with the VM.
mounts: []

containerd:
  system: false
  user: false

ssh:
  # Fixed port so IDEs (JetBrains Gateway / Remote Development) keep working after restarts.
  localPort: $LIMA_SSH_PORT
  loadDotSSHPubKeys: false
  forwardAgent: false
  forwardX11: false
  forwardX11Trusted: false
  overVsock: false

# Belt and braces (plain mode already disables dynamic forwarding).
portForwards:
  - guestIP: "0.0.0.0"
    proto: any
    ignore: true

# Do not copy host HTTP(S)_PROXY variables (which may contain credentials) into the VM.
propagateProxyEnv: false

hostResolver:
  enabled: true
EOF
}

vm_create() {
  need_cmd limactl "Run './sandbox setup' first."
  LIMA_INSTANCE="agent-$NAME"
  LIMA_SSH_PORT="$(lima_pick_port)"
  save_sandbox_env
  lima_render_yaml > "$SBX_DIR/lima.yaml"
  log "Creating Lima VM '$LIMA_INSTANCE' (${CPUS} CPU, ${MEMORY_GIB} GiB RAM, ${DISK_GIB} GiB disk)"
  limactl create --tty=false --name="$LIMA_INSTANCE" "$SBX_DIR/lima.yaml"
  vm_start
}

vm_start() {
  limactl start --tty=false "$LIMA_INSTANCE"
}

vm_stop() {
  if [ "$(vm_status)" = running ]; then
    limactl stop "$LIMA_INSTANCE"
  fi
}

vm_destroy() {
  if limactl list --format '{{.Name}}' 2>/dev/null | grep -qx "$LIMA_INSTANCE"; then
    limactl delete --force "$LIMA_INSTANCE"
  fi
}

vm_status() {
  local s
  s="$(limactl list --format '{{.Status}}' "$LIMA_INSTANCE" 2>/dev/null || true)"
  case "$s" in
    Running) echo running ;;
    Stopped) echo stopped ;;
    "")      echo missing ;;
    *)       echo "$s" | tr 'A-Z' 'a-z' ;;
  esac
}

# Run a command as root inside the VM (stdin is passed through). Uses Lima's own admin
# user (which has sudo); the 'agent' user never has sudo.
vm_admin_exec() {
  limactl shell --workdir / "$LIMA_INSTANCE" sudo -n "$@"
}

vm_admin_shell() {
  limactl shell --workdir / "$LIMA_INSTANCE" sudo -i
}

vm_ssh_endpoint() {
  echo "127.0.0.1 $LIMA_SSH_PORT"
}
